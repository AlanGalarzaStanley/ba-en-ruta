export type TourKey = keyof TourCopy
const TABLE: Record<Lang, TourCopy> = { es, en, pt }

export function tt(lang: Lang, key: TourKey, vars: Record<string, string | number> = {}): string {
  return TABLE[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""))
}

export const TOUR_COPY = TABLE
